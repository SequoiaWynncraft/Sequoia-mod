"""Regenerate the bundled gathering nodes from the Wynncraft API.

The API calls all four Dernic node kinds plain DERNIC and Molten Eel fishing spots MOLTEN, like
Molten ore, with no field that says which profession a node is. This keeps the names the bundled
file has for them (DERNIC_ORE, DERNIC_TREE, DERNIC_CROPS, DERNIC_FISH, MOLTEN, MOLTEN_EEL) by the
rules GatheringNodeNames applies in the mod: a wall or corner node is ore, and any other node takes
the name of the bundled node at its position, or else of the nearest bundled node of its material.

Run from the repository root: python scripts/gathering_nodes.py
"""
from datetime import datetime, timezone
from email.utils import parsedate_to_datetime
import json
from pathlib import Path
import urllib.request

NODES_URL = "https://api.wynncraft.com/v3/map/gathering-nodes"
TERRITORIES_URL = "https://api.wynncraft.com/v3/guild/list/territory"
BUNDLED = Path("src/main/resources/assets/seq/map/gathering-nodes.json")

# The API's shared name, the name for its ore, and the names the bundled file can tell apart.
SHARED = {
    "DERNIC": ("DERNIC_ORE", {"DERNIC_ORE", "DERNIC_TREE", "DERNIC_CROPS", "DERNIC_FISH"}),
    "MOLTEN": ("MOLTEN", {"MOLTEN", "MOLTEN_EEL"}),
}
# Plain DERNIC nodes the API still lists that 351c0fd removed as leftovers: two groups of four with
# no other node within 40 blocks, one 52 to 56 and the other 280 to 296 blocks from the nearest
# Dernic node of a known kind.
STRAY = {
    (632, 22, -1220), (638, 22, -1227), (644, 22, -1208), (652, 22, -1214),
    (1089, 68, -1059), (1092, 68, -1054), (1094, 68, -1053), (1095, 68, -1056),
}


def position(node):
    return node["x"], node["y"], node["z"]


def name(node, bundled_by_material):
    shared = SHARED.get(node["resource"])
    if shared is None:
        return node["resource"]
    ore, _ = shared
    if node["type"] in ("CORNER", "WALL"):
        return ore
    known = bundled_by_material[node["resource"]]
    if not known:
        return node["resource"]
    here = position(node)
    nearest = min(known, key=lambda other: sum((a - b) ** 2 for a, b in zip(here, position(other))))
    return nearest["resource"]


def territory(node, territories):
    """The territory whose rectangle holds the node, start inclusive and end exclusive, as in the old export."""
    for territory_name, details in territories.items():
        start, end = details["location"]["start"], details["location"]["end"]
        if (min(start[0], end[0]) <= node["x"] < max(start[0], end[0])
                and min(start[1], end[1]) <= node["z"] < max(start[1], end[1])):
            return territory_name
    return None


def regenerate(api_nodes, bundled_nodes, territories, fetched_at, api_version):
    bundled_by_material = {
        material: [node for node in bundled_nodes if node["resource"] in names]
        for material, (_, names) in SHARED.items()
    }
    bundled_at = {position(node): node for node in bundled_nodes}
    data = []
    for node in api_nodes:
        if node["resource"] == "DERNIC" and position(node) in STRAY:
            continue
        old = bundled_at.get(position(node))
        data.append({
            "x": node["x"],
            "y": node["y"],
            "z": node["z"],
            "angle": node["angle"],
            "type": node["type"],
            "resource": name(node, bundled_by_material),
            "level": node["level"],
            # The mod finds territories from the live list; this only labels the file.
            "territory": old["territory"] if old else territory(node, territories),
            "cluster_id": None,
        })
    return {
        "data": data,
        "meta": {
            "source": NODES_URL,
            "apiVersion": api_version,
            "count": len(data),
            "fetchedAt": fetched_at,
            "notes": "Generated by scripts/gathering_nodes.py. The API names every Dernic kind DERNIC and "
                     "Molten Eel MOLTEN; their names here come from the previous file. Eight stray DERNIC "
                     "nodes are left out (see 351c0fd).",
        },
    }


def fetch(url):
    request = urllib.request.Request(url, headers={"Accept": "application/json", "User-Agent": "Sequoia-Mod"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response), response.headers


def main():
    api_nodes, headers = fetch(NODES_URL)
    territories, _ = fetch(TERRITORIES_URL)
    fetched = parsedate_to_datetime(headers["Date"]) if headers.get("Date") else datetime.now(timezone.utc)
    bundled_nodes = json.loads(BUNDLED.read_text())["data"]
    document = regenerate(api_nodes, bundled_nodes, territories,
                          fetched.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), headers.get("version"))
    BUNDLED.write_text(json.dumps(document, indent=2))
    print(f"Wrote {document['meta']['count']} nodes from API {document['meta']['apiVersion']} to {BUNDLED}.")


if __name__ == "__main__":
    main()
